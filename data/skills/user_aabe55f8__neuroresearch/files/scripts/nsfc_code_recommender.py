def recommend_subcode(code, text):
    """在一级代码内挑选最匹配的二级代码（基于特异信号词打分）。"""
    low = text.lower()
    sig = SUB_SIGNAL.get(code, {})
    best_sub, best_name, best_score, best_hit = None, None, 0, []
    for sub, name in CODE_DB[code]["sub"].items():
        phrases = sig.get(sub, [])
        hit = [p for p in phrases if p in low]
        score = len(hit)
        if score > best_score:
            best_score, best_sub, best_name, best_hit = score, sub, name, hit
    if best_sub is not None:
        return best_sub, best_name, best_hit
    # 无特异信号命中：返回该代码第一个（通用）二级
    first_sub = next(iter(CODE_DB[code]["sub"].items()))
    return first_sub[0], first_sub[1], []


def axis_judgment(text):
    """判定机制 vs 修复轴心（聚焦 H09 vs H17 决策）。"""
    low = text.lower()
    m = sum(1 for kw in MECHANISM_KEYWORDS if kw in low)
    r = sum(1 for kw in REPAIR_KEYWORDS if kw in low)
    if m >= r:
        verdict = "机制主导型"
        note = "主要贡献偏向揭示分子/细胞机制 → 优先考虑 H09（H0910 神经损伤修复）或 H17（H1701 创伤），按创伤特异性强弱定夺。"
    else:
        verdict = "修复主导型"
        note = "主要贡献偏向修复/再生策略 → 优先考虑 H09（H0910）+ H28 方法学，或主报 H28。"
    return verdict, m, r, note


def rate_context(code):
    """返回该代码的中标率背景字符串。"""
    lines = []
    if code in CLINICAL_SPECIAL:
        rows = CLINICAL_SPECIAL[code]
        parts = []
        for yr in (2023, 2024, 2025):
            if yr in rows:
                ap, gr = rows[yr]
                rate = gr / ap * 100 if ap else 0
                parts.append(f"{yr} 临床专项 {ap}申/{gr}资({rate:.1f}%)")
        if parts:
            lines.append("　· 临床专项(按代码)： " + "；".join(parts))
    return "\n".join(lines)


