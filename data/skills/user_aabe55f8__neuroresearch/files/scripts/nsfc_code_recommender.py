def load_text(args):
    """从 -t / -f / stdin 读取研究内容文本。"""
    if args.text:
        return args.text
    if args.file:
        with open(args.file, "r", encoding="utf-8") as fh:
            return fh.read()
    if not sys.stdin.isatty():
        return sys.stdin.read()
    return ""


def score_codes(text):
    """对每段一级代码评分，返回列表 [(code, score, matched_keywords)]。"""
    low = text.lower()
    results = []
    for code, info in CODE_DB.items():
        matched = [kw for kw in info["keywords"] if kw in low]
        # 命中二级精确词额外加权（如「颅脑损伤」命中 H17 比泛「神经」更特异）
        score = len(matched)
        if score > 0:
            results.append((code, score, matched))
    results.sort(key=lambda x: x[1], reverse=True)
    return results


