# ---------------------------------------------------------------
# 便捷访问器
# ---------------------------------------------------------------
def get_domain(key):
    """返回某方向的配置 dict；key 不区分大小写，容错常用别名。"""
    if key in DOMAINS:
        return DOMAINS[key]
    alias = {"anime": "动漫", "动画": "动漫", "tv": "电视剧", "movie": "电影",
             "剧": "电视剧", "影": "电影"}
    norm = alias.get(key, key)
    if norm in DOMAINS:
        return DOMAINS[norm]
    raise KeyError(f"未知方向：{key}（可选：{list(DOMAINS)}）")


def dim_labels(overrides=None):
    """返回 [中文维度名, ...]，overrides 形如 {'ensemble':'群像度'} 可局部覆盖。"""
    labels = [label for _, label in DIMS]
    if overrides:
        # overrides 按 key 或按 index 覆盖均可
        for k, v in overrides.items():
            for i, (dk, _) in enumerate(DIMS):
                if dk == k:
                    labels[i] = v
    return labels
